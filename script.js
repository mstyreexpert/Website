// Tijd in Brussel, ongeacht waar de bezoeker zit.
function brusselsNow() {
  const parts = new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Europe/Brussels',
    weekday: 'short',
    hour: '2-digit',
    minute: '2-digit',
    hour12: false
  }).formatToParts(new Date());

  const get = (type) => parts.find((p) => p.type === type)?.value ?? '';
  const days = { Sun: 0, Mon: 1, Tue: 2, Wed: 3, Thu: 4, Fri: 5, Sat: 6 };

  return {
    day: days[get('weekday')] ?? new Date().getDay(),
    minutes: Number(get('hour')) * 60 + Number(get('minute'))
  };
}

function toMinutes(hhmm) {
  const [h, m] = hhmm.split(':').map(Number);
  return h * 60 + m;
}

function updateStatus() {
  const dict = translations[currentLang];
  const now = brusselsNow();
  const days = (dict.day_names || '').split(',');

  const fill = (template, values) =>
    (template || '').replace(/\{(\w+)\}/g, (_, k) => values[k] ?? '');

  document.querySelectorAll('[data-open][data-close]').forEach((branch) => {
    const open = toMinutes(branch.dataset.open);
    const close = toMinutes(branch.dataset.close);
    const isOpen = now.day !== 0 && now.minutes >= open && now.minutes < close;

    const tag = branch.querySelector('[data-status]');
    const text = branch.querySelector('[data-status-text]');
    const detail = branch.querySelector('[data-status-detail]');

    if (tag && text) {
      tag.classList.toggle('is-open', isOpen);
      tag.classList.toggle('is-closed', !isOpen);
      text.textContent = isOpen ? dict.status_open : dict.status_closed;
    }
    if (!detail) return;

    // Nuttiger dan alleen "gesloten": wanneer kan ik dan wél terecht?
    if (isOpen) {
      const left = close - now.minutes;
      detail.textContent = left <= 60
        ? fill(dict.closes_soon, { min: left })
        : fill(dict.open_until, { time: branch.dataset.close });
    } else if (now.day !== 0 && now.minutes < open) {
      detail.textContent = fill(dict.opens_at, { time: branch.dataset.open });
    } else {
      // na sluitingstijd, of zondag: eerstvolgende dag die geen zondag is
      let next = (now.day + 1) % 7;
      if (next === 0) next = 1;
      const label = next === (now.day + 1) % 7 && dict.day_tomorrow
        ? dict.day_tomorrow
        : days[next] || '';
      detail.textContent = fill(dict.opens_on, { day: label, time: branch.dataset.open });
    }
    detail.classList.toggle('is-open', isOpen);
    detail.classList.toggle('is-closed', !isOpen);
  });
}

