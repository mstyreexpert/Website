// De prijzen komen uit de tabellen op de pagina, niet uit een tweede lijst.
// Pas je een prijs aan in index.html, dan volgt de kiezer vanzelf.
function readPrices(panelId) {
  const map = new Map();
  document.querySelectorAll(`#${panelId} .price-table tbody tr`).forEach((row) => {
    const [sizeCell, priceCell] = row.querySelectorAll('td');
    if (!sizeCell || !priceCell) return;
    const nums = (sizeCell.textContent.match(/\d+/g) || []).map(Number);
    if (!nums.length) return;
    const from = nums[0];
    const to = nums.length > 1 ? nums[1] : nums[0];
    const price = priceCell.textContent.trim();
    for (let inch = from; inch <= to; inch++) map.set(inch, price);
  });
  return map;
}

function initFinder() {
  const host = document.getElementById('finderSizes');
  const out = document.getElementById('finderOut');
  if (!host || !out) return;

  const nieuw = readPrices('panel-nieuw');
  const occasie = readPrices('panel-occasie');
  const sizes = [...new Set([...nieuw.keys(), ...occasie.keys()])].sort((a, b) => a - b);
  if (!sizes.length) return;

  const render = (inch) => {
    const dict = translations[currentLang];
    const cell = (label, price) => `
      <div class="finder-result">
        <span class="lbl">${label}</span>
        <span class="val${price ? '' : ' none'}">${price || dict.finder_none}</span>
      </div>`;
    out.innerHTML = cell(dict.finder_new, nieuw.get(inch)) + cell(dict.finder_used, occasie.get(inch));
  };

  host.innerHTML = '';
  sizes.forEach((inch) => {
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = 'size-btn';
    btn.textContent = `${inch}"`;
    btn.setAttribute('aria-pressed', 'false');
    btn.addEventListener('click', () => {
      host.querySelectorAll('.size-btn').forEach((b) =>
        b.setAttribute('aria-pressed', String(b === btn)));
      render(inch);
      host.dataset.selected = String(inch);
    });
    host.appendChild(btn);
  });

  // bij het wisselen van taal de labels meenemen
  document.addEventListener('ms:language', () => {
    if (host.dataset.selected) render(Number(host.dataset.selected));
  });
}

/* ------------------------------------------------- rustige animaties --- */

function initReveal() {
  const els = document.querySelectorAll('.reveal');
  if (!els.length) return;

  const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  if (reduced || !('IntersectionObserver' in window)) {
    els.forEach((el) => el.classList.add('in'));
    return;
  }

  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add('in');
      observer.unobserve(entry.target);
    });
  }, { rootMargin: '0px 0px -8% 0px', threshold: 0.05 });

  els.forEach((el) => observer.observe(el));
}

function initToTop() {
  const btn = document.getElementById('toTop');
  if (!btn) return;
  const onScroll = () => btn.classList.toggle('show', window.scrollY > 700);
  window.addEventListener('scroll', onScroll, { passive: true });
  onScroll();
  btn.addEventListener('click', () => {
    const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    window.scrollTo({ top: 0, behavior: reduced ? 'auto' : 'smooth' });
  });
}

