const SUPPORTED = Object.keys(translations);
let currentLang = 'nl';

function changeLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  const dict = translations[lang];

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const value = dict[el.dataset.i18n];
    if (value !== undefined) el.textContent = value;
  });

  document.documentElement.lang = lang;
  if (dict.meta_title) document.title = dict.meta_title;

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.getAttribute('lang') === lang);
  });

  try { localStorage.setItem('ms-lang', lang); } catch (e) { /* privémodus */ }

  document.dispatchEvent(new CustomEvent('ms:language', { detail: { lang } }));
  updateStatus();
}

function initLanguage() {
  let lang = null;
  try { lang = localStorage.getItem('ms-lang'); } catch (e) { /* privémodus */ }
  if (!lang) {
    const browser = (navigator.language || 'nl').slice(0, 2).toLowerCase();
    lang = SUPPORTED.includes(browser) ? browser : 'nl';
  }
  changeLanguage(lang);
}

