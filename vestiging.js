const SUPPORTED = Object.keys(branchText);
const SLUG = document.body.dataset.branch;
let currentLang = 'nl';

function dictFor(lang) {
  const b = branchText[lang];
  return { ...b._shared, ...(b._branches[SLUG] || {}) };
}

function changeLanguage(lang) {
  if (!branchText[lang]) return;
  currentLang = lang;
  const dict = dictFor(lang);

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const value = dict[el.dataset.i18n];
    if (value !== undefined) el.textContent = value;
  });

  document.documentElement.lang = lang;
  if (dict.page_title) document.title = dict.page_title;

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.getAttribute('lang') === lang);
  });

  try { localStorage.setItem('ms-lang', lang); } catch (e) { /* privemodus */ }
  updateStatus();
}

function brusselsNow() {
  const parts = new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Europe/Brussels', weekday: 'short',
    hour: '2-digit', minute: '2-digit', hour12: false,
  }).formatToParts(new Date());
  const get = (t) => parts.find((p) => p.type === t)?.value ?? '';
  const days = { Sun: 0, Mon: 1, Tue: 2, Wed: 3, Thu: 4, Fri: 5, Sat: 6 };
  return { day: days[get('weekday')] ?? new Date().getDay(),
           minutes: Number(get('hour')) * 60 + Number(get('minute')) };
}

function updateStatus() {
  const dict = dictFor(currentLang);
  const now = brusselsNow();
  const days = (dict.day_names || '').split(',');
  const fill = (tpl, v) => (tpl || '').replace(/\{(\w+)\}/g, (_, k) => v[k] ?? '');

  document.querySelectorAll('[data-open][data-close]').forEach((card) => {
    const toMin = (s) => { const [h, m] = s.split(':').map(Number); return h * 60 + m; };
    const open = toMin(card.dataset.open);
    const close = toMin(card.dataset.close);
    const isOpen = now.day !== 0 && now.minutes >= open && now.minutes < close;

    const tag = card.querySelector('[data-status]');
    const text = card.querySelector('[data-status-text]');
    const detail = card.querySelector('[data-status-detail]');

    if (tag && text) {
      tag.classList.toggle('is-open', isOpen);
      tag.classList.toggle('is-closed', !isOpen);
      text.textContent = isOpen ? dict.status_open : dict.status_closed;
    }
    if (!detail) return;

    if (isOpen) {
      const left = close - now.minutes;
      detail.textContent = left <= 60
        ? fill(dict.closes_soon, { min: left })
        : fill(dict.open_until, { time: card.dataset.close });
    } else if (now.day !== 0 && now.minutes < open) {
      detail.textContent = fill(dict.opens_at, { time: card.dataset.open });
    } else {
      let next = (now.day + 1) % 7;
      if (next === 0) next = 1;
      const label = next === (now.day + 1) % 7 && dict.day_tomorrow
        ? dict.day_tomorrow : days[next] || '';
      detail.textContent = fill(dict.opens_on, { day: label, time: card.dataset.open });
    }
    detail.classList.toggle('is-open', isOpen);
    detail.classList.toggle('is-closed', !isOpen);
  });
}

document.addEventListener('DOMContentLoaded', () => {
  let lang = null;
  try { lang = localStorage.getItem('ms-lang'); } catch (e) { /* privemodus */ }
  if (!lang) {
    const browser = (navigator.language || 'nl').slice(0, 2).toLowerCase();
    lang = SUPPORTED.includes(browser) ? browser : 'nl';
  }
  changeLanguage(lang);
  setInterval(updateStatus, 60000);

  const year = document.getElementById('year');
  if (year) year.textContent = String(new Date().getFullYear());
});
